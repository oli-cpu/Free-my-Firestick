"""Standalone APK build for Free My TV (Fire TV) - needs only Python 3 and a JDK (keytool/jarsigner).

    python3 tools/build_apk.py . FreeMyTV-FireTV.apk

The project dir must contain web/www/ (the web UI), the two PNGs in
android/app/src/main/res/drawable-nodpi/ and signing/freemytv.keystore (created
on first run). No Android SDK required: classes.dex, AndroidManifest.xml and
resources.arsc are generated by dex.py, axml.py and arsc.py in this folder.
The bytecode in app_code.py mirrors the Java sources in android/app/src/main/java.
"""
import os
import subprocess
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import app_code
import arsc
import axml
from axml import E, A, P, ref, hexint

PKG = 'org.freemytv.firetv'
VERSION_CODE = 10302
VERSION_NAME = '1.3.2-firetv'
THEME_BLACK_NOTITLE_FULLSCREEN = 0x0103000a   # @android:style/Theme.Black.NoTitleBar.Fullscreen
KS_PASS = 'freemytv'
KS_ALIAS = 'freemytv'


def build(project, out_apk):
    work = os.path.join(os.path.dirname(os.path.abspath(out_apk)), 'build', 'apk-work')
    os.makedirs(work, exist_ok=True)

    table, ids = arsc.write(PKG, [
        ('drawable', 0xFFFF, [('icon', 'res/drawable-nodpi/icon.png'), ('banner', 'res/drawable-nodpi/banner.png')]),
        ('xml', 0, [('a11y', 'res/xml/a11y.xml')]),
    ])

    manifest = E('manifest', [A('versionCode', VERSION_CODE), A('versionName', VERSION_NAME), P('package', PKG)], [
        E('uses-sdk', [A('minSdkVersion', 22), A('targetSdkVersion', 29)]),
        E('uses-permission', [A('name', 'android.permission.INTERNET')]),
        E('uses-feature', [A('name', 'android.hardware.touchscreen'), A('required', False)]),
        E('uses-feature', [A('name', 'android.software.leanback'), A('required', False)]),
        E('application', [A('theme', ref(THEME_BLACK_NOTITLE_FULLSCREEN)), A('label', 'Free My TV'),
                          A('icon', ref(ids['drawable/icon'])), A('allowBackup', False),
                          A('hardwareAccelerated', True), A('banner', ref(ids['drawable/banner']))], [
            E('activity', [A('label', 'Free My TV'), A('name', PKG + '.MainActivity'), A('exported', True),
                           A('launchMode', 2), A('screenOrientation', 0), A('configChanges', hexint(0x3ff0))], [
                E('intent-filter', [], [
                    E('action', [A('name', 'android.intent.action.MAIN')]),
                    E('category', [A('name', 'android.intent.category.LAUNCHER')]),
                    E('category', [A('name', 'android.intent.category.LEANBACK_LAUNCHER')]),
                ]),
                # Lets Free My TV be the device's home app (replaces the stock Fire TV home once that is disabled).
                E('intent-filter', [], [
                    E('action', [A('name', 'android.intent.action.MAIN')]),
                    E('category', [A('name', 'android.intent.category.HOME')]),
                    E('category', [A('name', 'android.intent.category.DEFAULT')]),
                ]),
            ]),
            E('service', [A('label', 'Free My TV Home-Taste'), A('name', PKG + '.HomeService'),
                          A('permission', 'android.permission.BIND_ACCESSIBILITY_SERVICE'), A('exported', True),
                          A('process', ':home')], [
                E('intent-filter', [], [E('action', [A('name', 'android.accessibilityservice.AccessibilityService')])]),
                E('meta-data', [A('name', 'android.accessibilityservice'), A('resource', ref(ids['xml/a11y']))]),
            ]),
        ]),
    ])
    a11y = E('accessibility-service', [
        A('description', 'Free My TV: shows Free My TV whenever the Fire TV home comes up. '
                         'Reads only which app is in front, no screen content.'),
        A('accessibilityEventTypes', hexint(0x20)),        # typeWindowStateChanged
        A('accessibilityFeedbackType', hexint(0x10)),      # feedbackGeneric
        A('notificationTimeout', 0),
        A('accessibilityFlags', hexint(0)),
        A('canRetrieveWindowContent', False),
    ])

    files = []   # (zip name, bytes, stored)
    files.append(('AndroidManifest.xml', axml.write(manifest), False))
    files.append(('classes.dex', app_code.build().build(), False))
    files.append(('resources.arsc', table, True))
    files.append(('res/drawable-nodpi/icon.png', open(os.path.join(project, 'android/app/src/main/res/drawable-nodpi/icon.png'), 'rb').read(), True))
    files.append(('res/drawable-nodpi/banner.png', open(os.path.join(project, 'android/app/src/main/res/drawable-nodpi/banner.png'), 'rb').read(), True))
    files.append(('res/xml/a11y.xml', axml.write(a11y), False))
    www = os.path.join(project, 'web', 'www')
    for root, dirs, names in os.walk(www):
        dirs.sort()
        for n in sorted(names):
            full = os.path.join(root, n)
            rel = os.path.relpath(full, www).replace(os.sep, '/')
            files.append(('assets/www/' + rel, open(full, 'rb').read(), n.endswith('.png')))

    unsigned = os.path.join(work, 'unsigned.apk')
    with zipfile.ZipFile(unsigned, 'w') as z:
        for name, data, stored in files:
            info = zipfile.ZipInfo(name, date_time=(2026, 10, 29, 0, 0, 0))
            info.compress_type = zipfile.ZIP_STORED if stored else zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)

    ks = os.path.join(project, 'signing', 'freemytv.keystore')
    if not os.path.exists(ks):
        os.makedirs(os.path.dirname(ks), exist_ok=True)
        subprocess.check_call(['keytool', '-genkeypair', '-keystore', ks, '-storetype', 'PKCS12',
                               '-storepass', KS_PASS, '-keypass', KS_PASS, '-alias', KS_ALIAS,
                               '-keyalg', 'RSA', '-keysize', '2048', '-validity', '10950',
                               '-dname', 'CN=Free My TV for Fire TV, O=FreeMyTV'])
    signed = os.path.join(work, 'signed.apk')
    subprocess.check_call(['jarsigner', '-keystore', ks, '-storepass', KS_PASS, '-keypass', KS_PASS,
                           '-sigalg', 'SHA256withRSA', '-digestalg', 'SHA-256',
                           '-signedjar', signed, unsigned, KS_ALIAS], stdout=subprocess.DEVNULL)
    zipalign(signed, out_apk)
    return files


def zipalign(src, dst, align=4):
    """Re-write the zip so every STORED entry's data starts on a 4-byte boundary (like zipalign).
    Entry contents and order are unchanged, so the v1 (JAR) signature stays valid."""
    zin = zipfile.ZipFile(src)
    infos = zin.infolist()
    blob = open(src, 'rb').read()
    cd_offset = int.from_bytes(blob[blob.rindex(b'PK\x05\x06') + 16:][:4], 'little')
    bounds = sorted(i.header_offset for i in infos) + [cd_offset]
    with open(dst, 'wb') as f:
        central = []
        for info in infos:
            # copy everything of the entry (data + optional data descriptor) verbatim
            start = info.header_offset
            end = bounds[bounds.index(start) + 1]
            hdr = blob[start:start + 30]
            assert hdr[:4] == b'PK\x03\x04'
            nlen = int.from_bytes(hdr[26:28], 'little')
            elen = int.from_bytes(hdr[28:30], 'little')
            name = blob[start + 30:start + 30 + nlen]
            data = blob[start + 30 + nlen + elen:end]
            offset = f.tell()
            extra = b''
            if info.compress_type == zipfile.ZIP_STORED:
                pad = (align - (offset + 30 + nlen) % align) % align
                extra = b'\x00' * pad
            hdr = bytearray(hdr)
            hdr[28:30] = len(extra).to_bytes(2, 'little')
            f.write(hdr + name + extra + data)
            central.append((info, offset, name))
        cd_start = f.tell()
        for info, offset, name in central:
            ver_made = (info.create_system << 8) | info.create_version
            dt = info.date_time
            dosdate = ((dt[0] - 1980) << 9) | (dt[1] << 5) | dt[2]
            dostime = (dt[3] << 11) | (dt[4] << 5) | (dt[5] // 2)
            rec = b'PK\x01\x02' + ver_made.to_bytes(2, 'little') + info.extract_version.to_bytes(2, 'little') + \
                info.flag_bits.to_bytes(2, 'little') + info.compress_type.to_bytes(2, 'little') + \
                dostime.to_bytes(2, 'little') + dosdate.to_bytes(2, 'little') + \
                (info.CRC & 0xffffffff).to_bytes(4, 'little') + info.compress_size.to_bytes(4, 'little') + \
                info.file_size.to_bytes(4, 'little') + len(name).to_bytes(2, 'little') + (0).to_bytes(2, 'little') + \
                (0).to_bytes(2, 'little') + (0).to_bytes(2, 'little') + info.internal_attr.to_bytes(2, 'little') + \
                info.external_attr.to_bytes(4, 'little') + offset.to_bytes(4, 'little') + name
            f.write(rec)
        cd_end = f.tell()
        n = len(central)
        f.write(b'PK\x05\x06' + (0).to_bytes(4, 'little') + n.to_bytes(2, 'little') + n.to_bytes(2, 'little') +
                (cd_end - cd_start).to_bytes(4, 'little') + cd_start.to_bytes(4, 'little') + (0).to_bytes(2, 'little'))


if __name__ == '__main__':
    files = build(sys.argv[1], sys.argv[2])
    print('built', sys.argv[2], 'with', len(files), 'entries')
